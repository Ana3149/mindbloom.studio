// Bundles the public site (HTML pages + assets/) into a single Cloudflare Worker
// script at .worker/index.js. Every file is embedded, so deploying needs only an
// API token (no separate asset upload). Run: npm run build && npm run deploy
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.ico': 'image/x-icon',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = [
  ...readdirSync(root).filter((f) => f.endsWith('.html')).map((f) => join(root, f)),
  ...walk(join(root, 'assets')),
];

const entries = files.map((file) => {
  const path = '/' + relative(root, file).split('\\').join('/');
  const type = TYPES[extname(file)] || 'application/octet-stream';
  const text = type.startsWith('text/') || type === 'image/svg+xml';
  const buf = readFileSync(file);
  return { path, type, text, body: text ? buf.toString('utf8') : buf.toString('base64') };
});

const worker = `// Generated by scripts/build-worker.mjs — do not edit by hand.
const FILES = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.path, { t: e.type, x: e.text, b: e.body }])))};

const SECURITY = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'X-Frame-Options': 'SAMEORIGIN',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
};

function decode(f) {
  if (f.x) return f.b;
  const bin = atob(f.b);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

function lookup(pathname) {
  if (pathname === '/' || pathname === '') return '/index.html';
  if (FILES[pathname]) return pathname;
  if (FILES[pathname + '.html']) return pathname + '.html';
  if (pathname.endsWith('/') && FILES[pathname + 'index.html']) return pathname + 'index.html';
  return null;
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.hostname.startsWith('www.')) {
      url.hostname = url.hostname.slice(4);
      return Response.redirect(url.toString(), 301);
    }
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method Not Allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
    }
    const key = lookup(decodeURIComponent(url.pathname));
    if (!key) {
      return new Response('<!DOCTYPE html><meta charset="utf-8"><title>Not found</title><p style="font-family:sans-serif;padding:2rem">Page not found. <a href="/">MindBloom Studio</a></p>', {
        status: 404, headers: { 'Content-Type': 'text/html; charset=utf-8', ...SECURITY },
      });
    }
    const f = FILES[key];
    const headers = {
      'Content-Type': f.t,
      'Cache-Control': key.startsWith('/assets/fonts/') ? 'public, max-age=31536000, immutable'
        : key.endsWith('.html') ? 'public, max-age=0, must-revalidate' : 'public, max-age=3600',
      ...SECURITY,
    };
    return new Response(request.method === 'HEAD' ? null : decode(f), { headers });
  },
};
`;

mkdirSync(join(root, '.worker'), { recursive: true });
writeFileSync(join(root, '.worker', 'index.js'), worker);
console.log(`Bundled ${entries.length} files into .worker/index.js (${(worker.length / 1024).toFixed(0)} KB)`);
